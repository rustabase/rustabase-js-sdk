// Turns a RustaBase schema (the list returned by GET /api/collections) into
// TypeScript declarations. Pure function: no network, no file system.

const opt = (field, key) =>
    field[key] !== undefined ? field[key] : field.options ? field.options[key] : undefined;

const many = (field) => Number(opt(field, "maxSelect") || 1) > 1;

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** "blog_posts" -> "BlogPosts"; names starting with a digit get a prefix. */
export function pascal(name) {
    const out = String(name)
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((p) => p[0].toUpperCase() + p.slice(1))
        .join("");
    return /^[0-9]/.test(out) ? "T" + out : out || "Table";
}

const key = (name) => (IDENT.test(name) ? name : JSON.stringify(name));

function tsType(field) {
    switch (field.type) {
        case "number":
            return "number";
        case "bool":
            return "boolean";
        case "select": {
            const values = opt(field, "values") || [];
            const one = values.length ? values.map((v) => JSON.stringify(v)).join(" | ") : "string";
            return many(field) ? `Array<${one}>` : one;
        }
        case "file":
        case "relation":
            return many(field) ? "string[]" : "string";
        case "json":
            return "unknown";
        case "geoPoint":
        case "geopoint":
            return "{ lon: number; lat: number }";
        default:
            // text, email, url, editor, date, autodate and unknown types
            return "string";
    }
}

/** Fields that never travel back to clients. */
const readable = (f) => f.type !== "password" && !f.hidden;

/** Fields a client may send when creating a row. */
const writable = (f) => f.type !== "autodate" && !(f.system && f.name === "id");

/**
 * @param {Array<object>} collections schema from GET /api/collections
 * @param {{ includeSystem?: boolean }} [options]
 * @returns {string} TypeScript source
 */
export function generateTypes(collections, options = {}) {
    const list = [...(collections || [])]
        .filter((c) => c && c.name && (options.includeSystem || !c.system))
        .sort((a, b) => a.name.localeCompare(b.name));

    const lines = [
        "// Generated by `npx rustabase gen-types`. Do not edit by hand;",
        "// run the command again after changing your tables.",
        "",
    ];
    const names = [];
    for (const c of list) {
        const T = pascal(c.name);
        names.push([c.name, T]);
        const fields = c.fields || [];
        lines.push(`/** Row of the \`${c.name}\` table (${c.type || "base"}). */`);
        lines.push(`export interface ${T} {`);
        if (!fields.some((f) => f.name === "id")) lines.push("    id: string;");
        for (const f of fields.filter(readable)) {
            lines.push(`    ${key(f.name)}: ${tsType(f)};`);
        }
        lines.push("    collectionId: string;");
        lines.push("    collectionName: string;");
        lines.push("    expand?: Record<string, unknown>;");
        lines.push("}", "");

        lines.push(`/** Data accepted when creating a \`${c.name}\` row. */`);
        lines.push(`export interface ${T}Create {`);
        if (c.type === "view") {
            lines.length -= 1;
            lines.push(`export type ${T}Create = never; // views are read-only`, "");
            continue;
        }
        for (const f of fields.filter(writable)) {
            const q = f.required ? "" : "?";
            lines.push(`    ${key(f.name)}${q}: ${tsType(f)};`);
        }
        if (c.type === "auth" && !fields.some((f) => f.name === "passwordConfirm")) {
            lines.push("    passwordConfirm?: string;");
        }
        lines.push("}", "");
    }

    lines.push("/** Every table, keyed by its name. */");
    lines.push("export interface Tables {");
    for (const [n, T] of names) lines.push(`    ${key(n)}: ${T};`);
    lines.push("}", "");
    lines.push("export type TableName = keyof Tables;", "");
    lines.push("/**");
    lines.push(" * Typed table access:");
    lines.push(' *     const posts = table(rb, "posts"); // Table<Posts>');
    lines.push(" */");
    lines.push("export function table<N extends TableName>(");
    lines.push('    rb: import("rustabase").RustaBase,');
    lines.push("    name: N,");
    lines.push('): import("rustabase").Table<Tables[N]> {');
    lines.push("    return rb.from<Tables[N]>(name);");
    lines.push("}", "");
    return lines.join("\n");
}
